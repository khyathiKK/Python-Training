num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))

def add(num1, num2):
    return num1 + num2

def sub(num1, num2):
    return num1 - num2

def mul(num1, num2):
    return num1 * num2

def div(num1, num2):
    return num1 / num2

def mod(num1, num2):
    return num1 % num2

print("Add:",add(num1, num2))
print("Sub:",sub(num1, num2))
print("Mul:",mul(num1, num2))
print("Div:",div(num1, num2))
print("Mod:",mod(num1, num2))

